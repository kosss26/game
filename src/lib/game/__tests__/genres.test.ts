import { catalogGenre } from '../genres';

test.each([
  ['Детектив', 'Детектив'],
  ['Детектив · семейная тайна', 'Детектив'],
  ['Триллер · прямой эфир', 'Триллер'],
  ['Фантастический триллер · петля времени', 'Триллер'],
  ['Мистический триллер', 'Триллер'],
  ['Триллер · ограбление', 'Триллер'],
  [null, ''],
])('groups %s under %s', (input, expected) => {
  expect(catalogGenre(input)).toBe(expected);
});
