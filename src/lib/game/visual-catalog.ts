/** Preserve exact resolved story text; do not mistake the phone brand for its message. */
export function evidenceText(theme: Extract<StoryVisual,{kind:'document'}>['theme'], body:string):string {
  const quotes=Array.from(body.matchAll(/«([^»]+)»/g),m=>m[1]);
  if(theme==='phone' && quotes.length)return quotes[quotes.length-1];
  return ['envelope','grid'].includes(theme) && quotes.length ? quotes.join('\n\n') : body;
}
